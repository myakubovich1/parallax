import { chromium } from 'playwright';
import { fileURLToPath } from 'node:url';
const out = fileURLToPath(new URL('./screens/', import.meta.url));
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto('http://localhost:5199/#wave-interference');
await p.waitForTimeout(500);
await p.click('.followup .chip:has-text("Make the waves cancel")');
await p.waitForTimeout(1200);
await p.hover('.term.tone-amber');
await p.waitForTimeout(200);
await p.screenshot({ path: out + 'wave-cancel-focus.png', fullPage: true });
await p.click('.ws-header .mode-option:has-text("Quick intuition")');
await p.goto('http://localhost:5199/#gradient-descent');
await p.click('.preset:has-text("Overshooting")');
await p.waitForTimeout(2600);
await p.hover('.term.tone-ice');
await p.screenshot({ path: out + 'gradient-overshoot.png' });
await b.close();
