import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://localhost:5199/';
import { fileURLToPath } from 'node:url';
const out = fileURLToPath(new URL('./screens/', import.meta.url));
const browser = await chromium.launch();
const errors = [];
async function page(w, h, opts = {}) {
  const ctx = await browser.newContext({ viewport: { width: w, height: h }, deviceScaleFactor: 1, ...opts });
  const p = await ctx.newPage();
  p.on('console', (m) => m.type() === 'error' && errors.push(`[${w}] ${m.text()}`));
  p.on('pageerror', (e) => errors.push(`[${w}] ${e.message}`));
  return p;
}
const p = await page(1440, 900);
await p.goto(base);
await p.waitForTimeout(800);
await p.screenshot({ path: out + 'entry-1440.png' });
await p.goto(base + '#wave-interference');
await p.waitForTimeout(900);
await p.screenshot({ path: out + 'wave-1440.png' });
await p.goto(base + '#gravitational-attraction');
await p.waitForTimeout(600);
await p.screenshot({ path: out + 'gravity-1440.png' });
await p.goto(base + '#gradient-descent');
await p.waitForTimeout(2500);
await p.screenshot({ path: out + 'gradient-1440.png' });
const m = await page(390, 844, { isMobile: true, hasTouch: true });
await m.goto(base);
await m.waitForTimeout(600);
await m.screenshot({ path: out + 'entry-390.png', fullPage: true });
await m.goto(base + '#wave-interference');
await m.waitForTimeout(800);
await m.screenshot({ path: out + 'wave-390.png', fullPage: true });
const ow = await m.evaluate(() => document.documentElement.scrollWidth - innerWidth);
const wide = await m.evaluate(() => [...document.querySelectorAll('body *')].filter((e) => { const r = e.getBoundingClientRect(); return r.width > 0 && r.right > innerWidth + 1 && !e.closest('.equation-scroll, .mode-selector'); }).map((e) => e.className || e.tagName).slice(0, 8));
console.log('elements past right edge:', wide);
console.log('mobile horizontal overflow px:', ow);
const t = await page(900, 1000);
await t.goto(base + '#wave-interference');
await t.waitForTimeout(600);
await t.screenshot({ path: out + 'wave-900.png' });
console.log('errors:', errors.length ? errors.join('\n') : 'none');
await browser.close();
