export function formatValue(value: number): string {
  return !Number.isFinite(value)
    ? 'No real value'
    : value !== 0 && (Math.abs(value) >= 1e5 || Math.abs(value) < 0.001)
      ? value.toExponential(3)
      : Number(value.toPrecision(5)).toString();
}
